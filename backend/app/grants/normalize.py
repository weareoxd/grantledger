# Organization words that are also surnames or given names, that join a couple's
# names ("SMITH JOHN AND MARY"), or that occur in Indigenous family names ("STANDING
# ON THE ROAD", "FIRST RIDER"). Treating them as organization markers would publish
# people named Wood, Park, St-Onge or Board, so they never count on their own.
# Cost: some organizations whose only marker is one of these get withheld.
NAME_COLLISIONS = frozenset(
    """
    AND ST STE SAINT SAINTE CO SA AG MD BV NV HOME FAMILY FAMILIES ARENA VILLA MANOR
    LODGE PARISH GUILD BURGER MART DOLLAR WOOD BANK PRESS POWER PORT PARK PARKS ROMAN CAMP
    KITCHEN CHARITY TEMPLE ARTS LOOMIS SAPUTO CHURCH VALLEY PLACE STORE MEN TO ON MY IN AT WE
    THE OF FOR BY OUT OUR YOUR FIRST BOARD
    """.split()
)

# Multi-word markers that stay reliable even though their words collide with names.
_ORG_PHRASES = re.compile(
    r"^(MD|M D) OF\b|\bFIRST NATIONS?\b|\bSCHOOL BOARD\b|\bBOARD OF\b|\bOF THE\b"
)

# Collision words that do mark an organization when they END a name of three or more
# words ("... LAND AND WATER BOARD"), where a surname is unlikely: Alberta lists people
# surname first, so a trailing word there is a given name.
_TRAILING_ORG_TOKENS = frozenset(
    "BOARD LODGE HOME BANK MANOR GUILD PRESS PLACE KITCHEN STORE CAMP MART PORT ARENA".split()
)

ORG_TOKENS = _ORG_CANDIDATES - NAME_COLLISIONS

_WORD = re.compile(r"[A-Z][A-Z'\-]*")


def looks_like_person(raw):
    """
    Heuristic: does this recipient name look like an individual's name?

    True for 2-6 purely alphabetic tokens with no organization marker and no digits.
    It errs toward withholding: a small organization with a two-word name and no
    marker ("ACME WIDGETS") is treated as a person. That trade-off is intentional
    for a public demo built on data whose licence excludes personal information.
    """
    key = normalize_name(raw)
    if not key or any(ch.isdigit() for ch in key):
        return False
    tokens = _WORD.findall(key)
    if not 2 <= len(tokens) <= 6:
        return False
    if len(tokens) != len(key.split()):
        return False  # stray symbols (e.g. "#", "+") point to an organization
    if _ORG_PHRASES.search(key):
        return False
    if len(tokens) >= 3 and tokens[-1] in _TRAILING_ORG_TOKENS:
        return False
    parts = {p for t in tokens for p in re.split(r"[-']", t) if p}
    return not parts & ORG_TOKENS
