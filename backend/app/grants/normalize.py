"""
Recipient name normalisation and the personal-name privacy filter.

Both sources name recipients differently: the federal file uses mixed case
("Carleton University") and sometimes inverts articles ("ROYAL WINNIPEG BALLET THE");
Alberta upper-cases everything ("UNIVERSITY OF CALGARY"). ``normalize_name`` produces
the canonical key both resolve to, so the same organization funded by both
governments lands on one ``Recipient``.

The Open Government Licences do not cover personal information, and Alberta's
file has no recipient-type column, so ``looks_like_person`` flags names that
look like an individual's. Flagged rows are kept (so ministry and program totals
stay complete) but re-pointed at a placeholder recipient with identifying
fields cleared.
"""

import re

from unidecode import unidecode

# Placeholder recipients (Recipient.is_placeholder = True)
WITHHELD_INDIVIDUAL = "INDIVIDUAL RECIPIENT (NAME WITHHELD)"
NOT_DISCLOSED = "RECIPIENT NOT DISCLOSED"
PLACEHOLDER_NAMES = (WITHHELD_INDIVIDUAL, NOT_DISCLOSED)

# Legal-form spellings collapsed to one token so "ACME LIMITED" == "ACME LTD.".
_LEGAL_FORMS = {
    "INCORPORATED": "INC",
    "INCORPOREE": "INC",
    "LIMITED": "LTD",
    "LIMITEE": "LTEE",
    "CORPORATION": "CORP",
}

# Legal forms written with spaces ("NORTHERN BIODIESEL L P").
_SPLIT_FORMS = {("L", "P"): "LP", ("G", "P"): "GP", ("L", "L", "P"): "LLP", ("U", "L", "C"): "ULC"}

_COOP = re.compile(r"\bCO[- ]OP\b")
_ELISION = re.compile(r"\b([LD])['’]")
_PUNCT_DROP = re.compile(r"[.'’`\"]")
_PUNCT_SPACE = re.compile(r"[,;:()\[\]/\\]")
_SPACES = re.compile(r"\s+")


def _collapse_split_forms(tokens):
    for parts, joined in _SPLIT_FORMS.items():
        n = len(parts)
        if len(tokens) > n and tuple(tokens[-n:]) == parts:
            return tokens[:-n] + [joined]
    return tokens


def normalize_name(raw):
    """Canonical matching key for a recipient name ('' when nothing usable is left)."""
    if not raw:
        return ""
    text = unidecode(str(raw)).upper()
    text = text.replace("&", " AND ")
    text = _ELISION.sub(r"\1 ", text)  # L'ASSOCIATION -> L ASSOCIATION, D'EDMONTON -> D EDMONTON
    text = _COOP.sub("COOP", text)
    text = _PUNCT_DROP.sub("", text)
    text = _PUNCT_SPACE.sub(" ", text)
    tokens = [_LEGAL_FORMS.get(t, t) for t in _SPACES.split(text.strip()) if t]
    tokens = _collapse_split_forms(tokens)
    # Leading or trailing article: "THE EXAMPLE FOUNDATION", "EXAMPLE FOUNDATION THE".
    if len(tokens) > 1 and tokens[0] == "THE":
        tokens = tokens[1:]
    if len(tokens) > 1 and tokens[-1] == "THE":
        tokens = tokens[:-1]
    return " ".join(tokens)[:500]


def clean_display(raw):
    """Trimmed, single-spaced original spelling for display."""
    return _SPACES.sub(" ", str(raw or "")).strip()[:500]


